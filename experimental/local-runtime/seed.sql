-- After a security sync the roles are rebuilt; drop dangling assignments and assign the synced roles.
IF OBJECT_ID('SECURITYUSERROLE') IS NOT NULL
BEGIN
    DELETE SECURITYUSERROLE WHERE SECURITYROLE NOT IN (SELECT RECID FROM SECURITYROLE);
    INSERT SECURITYUSERROLE (USER_, SECURITYROLE, ASSIGNMENTSTATUS)
    SELECT u.ID, r.RECID, 1 FROM USERINFO u CROSS JOIN SECURITYROLE r
    WHERE u.ID IN ('Admin', '-AOS-') AND r.AOTNAME IN ('-SYSADMIN-', 'SYSTEMUSER')
      AND NOT EXISTS (SELECT 1 FROM SECURITYUSERROLE x WHERE x.USER_ = u.ID AND x.SECURITYROLE = r.RECID);
END
